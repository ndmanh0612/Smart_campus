param([string]$Flutter='flutter')
$ErrorActionPreference='Stop'
$root=(Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$app=Join-Path $root 'flutter\app'
$logs=Join-Path $root 'docs\evidence'
if(Test-Path -LiteralPath $app){throw 'App exists. Inspect and resume there; scaffold will not overwrite it.'}
& $Flutter --version 2>&1 | Tee-Object -FilePath (Join-Path $logs 'flutter-version.txt')
if($LASTEXITCODE -ne 0){throw 'Install Flutter and Android SDK first'}
& $Flutter doctor -v 2>&1 | Tee-Object -FilePath (Join-Path $logs 'flutter-doctor.txt')
Push-Location (Join-Path $root 'flutter')
try{
 & $Flutter create --platforms web,android --org vn.smartcard --project-name smartcard_week1 app
 if($LASTEXITCODE -ne 0){throw 'Scaffold failed'}
 Copy-Item -LiteralPath 'template\pubspec.yaml' -Destination 'app\pubspec.yaml'
 Copy-Item -LiteralPath 'template\lib\main.dart' -Destination 'app\lib\main.dart'
 Copy-Item -LiteralPath 'template\lib\core' -Destination 'app\lib\core' -Recurse
 # Only replace the counter test just generated by flutter create in this new app.
 Copy-Item -LiteralPath 'template\test\camera_spike_test.dart' -Destination 'app\test\widget_test.dart'
 $manifest=Join-Path $app 'android\app\src\main\AndroidManifest.xml'
 [xml]$xml=Get-Content -LiteralPath $manifest
 $p=$xml.CreateElement('uses-permission');$p.SetAttribute('name','http://schemas.android.com/apk/res/android','android.permission.CAMERA');[void]$xml.DocumentElement.PrependChild($p);$xml.Save($manifest)
 $gradle=Join-Path $app 'android\app\build.gradle.kts'
 (Get-Content -LiteralPath $gradle -Raw).Replace('minSdk = flutter.minSdkVersion','minSdk = 24') | Set-Content -LiteralPath $gradle -Encoding utf8
 $properties=Join-Path $app 'android\gradle.properties'
 $settings=(Get-Content -LiteralPath $properties -Raw) -replace '(?m)^org.gradle.jvmargs=.*$','org.gradle.jvmargs=-Xmx2G -XX:MaxMetaspaceSize=768m -XX:+HeapDumpOnOutOfMemoryError'
 $settings+="`norg.gradle.workers.max=2`n"
 Set-Content -LiteralPath $properties -Value $settings -Encoding utf8
 Push-Location $app
 try{
  & $Flutter pub get;if($LASTEXITCODE -ne 0){throw 'pub get failed'}
  & $Flutter analyze 2>&1 | Tee-Object -FilePath (Join-Path $logs 'flutter-analyze.txt');if($LASTEXITCODE -ne 0){throw 'analyze failed'}
  & $Flutter test 2>&1 | Tee-Object -FilePath (Join-Path $logs 'flutter-test.txt');if($LASTEXITCODE -ne 0){throw 'Widget test failed'}
  & $Flutter build web --release 2>&1 | Tee-Object -FilePath (Join-Path $logs 'build-web.txt');if($LASTEXITCODE -ne 0){throw 'Web build failed'}
  & $Flutter build apk --debug 2>&1 | Tee-Object -FilePath (Join-Path $logs 'build-apk.txt');if($LASTEXITCODE -ne 0){throw 'APK build failed'}
  Get-FileHash -LiteralPath 'build\app\outputs\flutter-apk\app-debug.apk' | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $logs 'apk-sha256.json')
 }finally{Pop-Location}
}finally{Pop-Location}
